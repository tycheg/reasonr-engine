// PluginMain is the main package of a binary plugin: the plugins of the
// manifest register in init(), as in a linked binary.
func (m *Manifest) PluginMain() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by reasonr-build from the manifest. DO NOT EDIT.\n\n")
	b.WriteString("// Package main is a ReasonR binary plugin with the plugins of its manifest.\npackage main\n\n")
	paths := make([]string, 0, len(m.Plugins))
	for _, p := range m.Plugins {
		paths = append(paths, p.Path)
	}
	sort.Strings(paths)
	b.WriteString("import (\n")
	for _, p := range paths {
		fmt.Fprintf(&b, "\t_ %q\n", p)
	}
	b.WriteString(")\n\nfunc main() {}\n")
	return b.Bytes()
}

// PluginGoMod is the go.mod of a binary plugin for the binary of build
// information host: it requires every module of the binary at its version
// (MVS never goes below them), the replaced modules of the plugins, and
// the replacements of the binary and of the manifest. A module the binary
// took from a directory needs a replacement of the manifest when the
// plugin links it.
func (m *Manifest) PluginGoMod(host *debug.BuildInfo) ([]byte, error) {
	reqs := map[string]string{}
	replace := map[string]string{}
	for _, d := range host.Deps {
		r := d.Replace
		if d.Version == "(devel)" || r != nil && (r.Version == "" || r.Version == "(devel)") {
			// From a directory or a workspace: the manifest replaces it if
			// the plugin links it; otherwise the check of the built plugin
			// names it.
			continue
		}
		reqs[d.Path] = d.Version
		if r != nil {
			replace[d.Path+" "+d.Version] = r.Path + " " + r.Version
		}
	}
	for _, p := range m.Plugins {
		if mod := m.module(p.Path); mod != "" {
			if _, ok := reqs[mod]; !ok {
				reqs[mod] = p.Version
			}
		}
	}
	for k, dir := range m.Replace {
		mod, version, _ := strings.Cut(k, "@")
		if reqs[mod] == "" || reqs[mod] == "(devel)" {
			reqs[mod] = "v0.0.0-00010101000000-000000000000"
		}
		replace[strings.TrimSpace(mod+" "+version)] = dir
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "module %s\n\ngo %s\n\nrequire (\n", m.Module, strings.TrimPrefix(goRelease(host), "go"))
	paths := make([]string, 0, len(reqs))
	for p := range reqs {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		fmt.Fprintf(&b, "\t%s %s\n", p, reqs[p])
	}
	b.WriteString(")\n")
	if len(replace) > 0 {
		keys := make([]string, 0, len(replace))
		for k := range replace {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		b.WriteString("\nreplace (\n")
		for _, k := range keys {
			fmt.Fprintf(&b, "\t%s => %s\n", k, replace[k])
		}
		b.WriteString(")\n")
	}
	return b.Bytes(), nil
}

// goRelease is the Go release of a build without its experiments.
func goRelease(b *debug.BuildInfo) string {
	v, _, _ := strings.Cut(b.GoVersion, " ")
	return v
}

// BuildPlugin builds the plugins of the manifest as one binary plugin out
// for the engine binary host: with the binary's Go (GOTOOLCHAIN), its
// platform, -trimpath, tags and compiler flags. A plugin that would raise a
// module the binary contains is refused before the build, naming who
// requires the newer version; the built plugin is checked as the loader
// checks it.
func (m *Manifest) BuildPlugin(out, hostPath string, keep bool, log io.Writer) error {
	host, err := buildinfo.ReadFile(hostPath)
	if err != nil {
		return fmt.Errorf("--host %s: %v", hostPath, err)
	}
	have := map[string]*debug.Module{}
	for _, d := range host.Deps {
		have[d.Path] = d
	}
	for _, r := range []Requirement{m.Engine, m.Port} {
		if r.Path != "" && (have[r.Path] == nil || have[r.Path].Version != r.Version) {
			return fmt.Errorf("the manifest requires %s %s, the binary %s has %s", r.Path, r.Version, hostPath, version(have[r.Path]))
		}
	}
	gomod, err := m.PluginGoMod(host)
	if err != nil {
		return err
	}
	dir, err := os.MkdirTemp("", "reasonr-build")
	if err != nil {
		return err
	}
	if keep {
		fmt.Fprintln(log, "build directory:", dir)
	} else {
		defer os.RemoveAll(dir)
	}
	if err := os.WriteFile(filepath.Join(dir, "main.go"), m.PluginMain(), 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), gomod, 0o644); err != nil {
		return err
	}
	env := append(os.Environ(), "GOWORK=off", "GOFLAGS=", "CGO_ENABLED=1", "GOTOOLCHAIN="+goRelease(host))
	flags := []string{"build", "-buildmode=plugin"}
	for _, s := range host.Settings {
		switch {
		case s.Key == "-trimpath" && s.Value == "true":
			flags = append(flags, "-trimpath")
		case s.Key == "-tags" || s.Key == "-gcflags" || s.Key == "-asmflags":
			flags = append(flags, s.Key+"="+s.Value)
		case strings.HasPrefix(s.Key, "GO") && s.Key != "GOROOT":
			env = append(env, s.Key+"="+s.Value)
		}
	}
	gocmd := func(args ...string) ([]byte, error) {
		cmd := exec.Command("go", args...)
		cmd.Dir, cmd.Env = dir, env
		var stdout bytes.Buffer
		cmd.Stdout, cmd.Stderr = &stdout, log
		if err := cmd.Run(); err != nil {
			return nil, fmt.Errorf("go %s: %v", strings.Join(args, " "), err)
		}
		return stdout.Bytes(), nil
	}
	for _, p := range m.Plugins {
		if m.module(p.Path) == "" {
			if _, err := gocmd("get", p.Path+"@"+p.Version); err != nil {
				return err
			}
		}
	}
	if _, err := gocmd("mod", "tidy"); err != nil {
		return err
	}
	graph, err := gocmd("mod", "graph")
	if err != nil {
		return err
	}
	if m.Port.Path != "" {
		if err := oneVersion(graph, m.Port.Path); err != nil {
			return err
		}
	}
	linked, err := gocmd("list", "-deps", "-f", "{{with .Module}}{{.Path}} {{.Version}}{{end}}", ".")
	if err != nil {
		return err
	}
	if err := raised(linked, graph, have, m.module); err != nil {
		return err
	}
	if _, err := gocmd(append(flags, "-o", out, ".")...); err != nil {
		return err
	}
	built, err := buildinfo.ReadFile(out)
	if err != nil {
		return err
	}
	if diff := plugins.Compare(host, built); len(diff) > 0 {
		return fmt.Errorf("the built plugin does not match %s:\n  %s", hostPath, strings.Join(diff, "\n  "))
	}
	return nil
}

// raised checks the modules of the plugin's packages (go list -deps)
// against the binary's: one the plugin needs newer is an error naming the
// modules of the graph that require that version. Modules the manifest
// replaces are the author's: they are not compared.
func raised(linked, graph []byte, have map[string]*debug.Module, replaced func(string) string) error {
	seen := map[string]bool{}
	var b strings.Builder
	for _, line := range strings.Split(strings.TrimSpace(string(linked)), "\n") {
		path, v, ok := strings.Cut(line, " ")
		h := have[path]
		if !ok || seen[path] || h == nil || h.Replace != nil || h.Version == v || replaced(path) == path {
			continue
		}
		seen[path] = true
		var by []string
		for _, edge := range strings.Split(string(graph), "\n") {
			if from, to, ok := strings.Cut(edge, " "); ok && to == path+"@"+v {
				by = append(by, from)
			}
		}
		sort.Strings(by)
		fmt.Fprintf(&b, "\n  %s %s, the binary has %s (required by %s)", path, v, h.Version, strings.Join(by, ", "))
	}
	if b.Len() == 0 {
		return nil
	}
	return fmt.Errorf("the plugin needs other versions of modules the binary contains:%s", b.String())
}

func version(m *debug.Module) string {
	if m == nil {
		return "none"
	}
	return m.Version
}
